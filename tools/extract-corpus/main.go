package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/grafana/loki/v3/pkg/logql/syntax"
	"github.com/prometheus/prometheus/model/labels"
)

func main() {
	root := flag.String("loki", ".cache/loki-src", "Loki source tree")
	flag.Parse()
	set := map[string]struct{}{}
	for _, f := range []string{"pkg/logql/syntax/parser_test.go", "pkg/logql/engine_test.go"} {
		for _, s := range goStrings(filepath.Join(*root, f)) {
			if q, ok := normalise(s); ok {
				set[q] = struct{}{}
			}
		}
	}
	_ = filepath.Walk(filepath.Join(*root, "docs/sources/query"), func(p string, info os.FileInfo, err error) error {
		if err == nil && strings.HasSuffix(p, ".md") {
			for _, s := range mdLogQL(p) {
				if q, ok := normalise(s); ok {
					set[q] = struct{}{}
				}
			}
		}
		return nil
	})
	out := make([]string, 0, len(set))
	for q := range set {
		out = append(out, q)
	}
	sort.Strings(out)
	fmt.Println("# generated by tools/extract-corpus — do not edit")
	for _, q := range out {
		if strings.HasPrefix(q, "range:") {
			if k, rest, _ := strings.Cut(q, ":"); k == "range" && maxRangeFor(rest) > maxRange {
				continue
			}
		}
		fmt.Println(q)
	}
}

// maxRangeFor returns the largest lookback used in q's range selectors.
func maxRangeFor(q string) time.Duration {
	var mx time.Duration
	e, err := syntax.ParseExpr(q)
	if err != nil {
		return 0
	}
	e.Walk(func(x syntax.Expr) bool {
		if r, ok := x.(*syntax.LogRangeExpr); ok && r.Interval > mx {
			mx = r.Interval
		}
		return true
	})
	return mx
}

func goStrings(path string) []string {
	fs := token.NewFileSet()
	f, err := parser.ParseFile(fs, path, nil, 0)
	if err != nil {
		return nil
	}
	var out []string
	ast.Inspect(f, func(n ast.Node) bool {
		if bl, ok := n.(*ast.BasicLit); ok && bl.Kind == token.STRING {
			if s, err := strconv.Unquote(bl.Value); err == nil && strings.Contains(s, "{") {
				out = append(out, s)
			}
		}
		return true
	})
	return out
}

var fence = regexp.MustCompile("(?s)```logql\\n(.*?)```")

func mdLogQL(path string) []string {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil
	}
	var out []string
	for _, m := range fence.FindAllSubmatch(b, -1) {
		sc := bufio.NewScanner(strings.NewReader(string(m[1])))
		var cur []string
		for sc.Scan() {
			cur = append(cur, sc.Text())
		}
		out = append(out, strings.Join(cur, " "))
	}
	return out
}

// maxRange is the largest metric lookback the fixture supports: entries span
// a 90-minute window, so lookbacks beyond 90m evaluate against the same data
// and their float accumulation order is not contractually defined
// (spec §7.2). Longer ranges are dropped from the corpus.
const maxRange = 90 * time.Minute

// normalise parses q, rewrites every selector to {app=~".+"} and tags metric queries.
func normalise(q string) (string, bool) {
	e, err := syntax.ParseExpr(q)
	if err != nil {
		return "", false
	}
	all := []*labels.Matcher{labels.MustNewMatcher(labels.MatchRegexp, "app", ".+")}
	e.Walk(func(x syntax.Expr) bool {
		if m, ok := x.(*syntax.MatchersExpr); ok {
			m.Mts = all
		}
		return true
	})
	s := e.String()
	if _, isLog := e.(syntax.LogSelectorExpr); !isLog {
		s = "range:" + s
	}
	if strings.Contains(s, "\n") {
		return "", false
	}
	return s, true
}
